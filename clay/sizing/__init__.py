"""
Clay sizing layer: closed-form gm/Id-based sizing solver.

This package was split out of the original ``clay/sizing.py`` flat module
in R92 C / BL-127 to host the layout-aware cost-mixing wrapper alongside
the original closed-form sizing primitives. The full ``clay.sizing`` import
surface (``SKY130_MU_COX``, ``SizingResult``, ``closed_form_W``,
``solve_sizing``, ``gm_from_intent``, ``I_d_for_gm``) is preserved
byte-equal — only the file layout changed.

The math here uses the strong-inversion square-law approximation, which is
adequate for design-space exploration but NOT a substitute for a real
BSIM-extracted LUT. v0.0.12+ replaces the closed form with a sky130-
specific LUT generated by sweeping ngspice on a unit transistor.

Strong-inversion square-law equations:
    I_d = (1/2) * mu_Cox * (W/L) * V_OV^2
    g_m = mu_Cox * (W/L) * V_OV  =  sqrt(2 * mu_Cox * (W/L) * I_d)
    g_m / I_d = 2 / V_OV

Given (gm_id, I_d, L) we derive:
    V_OV  =  2 / gm_id
    W/L   =  (2 * I_d) / (mu_Cox * V_OV^2)
          =  (gm_id^2 * I_d) / (2 * mu_Cox)
    W     =  (W/L) * L

We expose:
  - ``closed_form_W``     : the formula above
  - ``solve_sizing``      : high-level helper from (device_kind, gm_id, I_d, L)
                            to W, given a PDK technology table.
  - ``gm_from_intent``    : compute gm from (gm/Id, I_d).
  - ``I_d_for_gm``        : inverse — I_d needed for a target gm at chosen gm/Id.

Layout-aware extensions (R92 C / BL-127):
  - ``layout_hook.layout_aware_sizing_cost``
  - ``layout_hook.select_layout_aware_sizing``
  - ``layout_hook.LayoutAwareSelection``
  - ``layout_hook.DEFAULT_LAMBDA_LAYOUT``
  - ``layout_hook.DEFAULT_LAMBDA_AREA``
  - ``layout_hook.DEFAULT_TARGET_CMRR_DB``
  - ``layout_hook.DEFAULT_FINGER_COUNT_RANGE``

These wrap ``clay.layout.cosizing.{joint_sweep,pareto_optimal,select_optimal}``
and ``clay.layout.DefaultMismatchCostHook`` for use inside sizing cost
functions. See ``docs/planning/CROSS_PROMPT_SCOPE.html`` §9.3 + §10.2 for
the API contract and lambda defaults the layout prompt provided.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Mapping


# Process technology table — strong-inversion μ·C_ox values (A/V²) per
# device kind, at typical conditions. These are rough textbook values for
# sky130 1.8V; future LUT-based replacement will be far more accurate
# (sub-Vth, velocity saturation, body effect, length dependence).
SKY130_MU_COX: Mapping[str, float] = {
    # Empirical sky130 BSIM-extracted approximations at L=0.5um
    "nmos":     200e-6,   # ~200 µA/V² for sky130_fd_pr__nfet_01v8
    "pmos":      70e-6,   # ~70 µA/V² for sky130_fd_pr__pfet_01v8
    "nmos_lvt": 250e-6,
    "pmos_lvt":  90e-6,
}


@dataclass(frozen=True)
class SizingResult:
    W: float            # in meters
    L: float            # in meters (input echoed back for convenience)
    V_OV: float         # in volts (derived)
    I_d: float          # in amperes (input echoed back)
    gm_id: float        # in 1/V (input echoed back)
    method: str = "closed_form_square_law"


def closed_form_W(
    device_kind: str,
    gm_id: float,
    I_d: float,
    L: float,
    *,
    mu_cox_table: Mapping[str, float] = SKY130_MU_COX,
) -> SizingResult:
    """Map design intent (gm/Id, I_d, L) to a physical W using square-law.

    Args:
        device_kind: 'nmos' / 'pmos' / 'nmos_lvt' / 'pmos_lvt' — must
            have an entry in ``mu_cox_table``.
        gm_id: target gm/I_d in V^-1 (typical range 5-25; smaller for
            strong-inversion / faster, larger for sub-Vth / efficient).
        I_d: drain current in amperes.
        L: channel length in meters.
        mu_cox_table: process technology lookup; defaults to sky130.

    Returns:
        SizingResult with derived W, V_OV, etc.

    Raises:
        KeyError if device_kind not in the table.
        ValueError on non-positive inputs.
    """
    if gm_id <= 0:
        raise ValueError(f"gm_id must be positive, got {gm_id}")
    if I_d <= 0:
        raise ValueError(f"I_d must be positive, got {I_d}")
    if L <= 0:
        raise ValueError(f"L must be positive, got {L}")
    if device_kind not in mu_cox_table:
        raise KeyError(
            f"device_kind {device_kind!r} not in mu_cox_table; "
            f"available: {list(mu_cox_table)}"
        )

    mu_cox = mu_cox_table[device_kind]
    V_OV = 2.0 / gm_id
    W_over_L = (gm_id * gm_id * I_d) / (2.0 * mu_cox)
    W = W_over_L * L

    return SizingResult(
        W=W,
        L=L,
        V_OV=V_OV,
        I_d=I_d,
        gm_id=gm_id,
    )


def solve_sizing(
    device_kind: str,
    *,
    gm_id: float,
    I_d: float,
    L: float | None = None,
    L_default: float = 0.5e-6,
    mu_cox_table: Mapping[str, float] = SKY130_MU_COX,
) -> SizingResult:
    """High-level convenience: pick a default L if not provided."""
    L_use = L if L is not None else L_default
    return closed_form_W(device_kind, gm_id, I_d, L_use,
                         mu_cox_table=mu_cox_table)


# ─── Inverse helpers ──────────────────────────────────────────

def gm_from_intent(gm_id: float, I_d: float) -> float:
    """Compute target gm from (gm/Id, I_d).

    Useful when a template wants to derive gm from a spec like
    'gm >= 2*pi*GBW*C_load', then back-solve I_d given a chosen gm/Id.
    """
    return gm_id * I_d


def I_d_for_gm(gm: float, gm_id: float) -> float:
    """Inverse: how much I_d do I need for a given gm at chosen gm/Id?"""
    if gm_id <= 0:
        raise ValueError("gm_id must be positive")
    return gm / gm_id


