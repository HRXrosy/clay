#!/usr/bin/env python3
"""Bootstrap or detect open-source SKY130 and GF180MCU PDK installations for Clay.

Supports:
  * Auto-detecting existing `PDK_ROOT`, `CLAY_SKY130_PATH`, `CLAY_GF180MCU_PATH`,
    Volare (`~/.volare/volare`), IIC-OSIC (`/foss/pdks`), or local `./pdks/`.
  * Installing upstream Apache-2.0 GF180MCU via git (`google/gf180mcu-pdk`)
    and SKY130A via `volare` (`pip install volare && volare enable --pdk sky130`).
  * Writing a ready-to-use `clay.toml` in the repository root.
"""
from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def detect_sky130() -> Path | None:
    candidates = []
    for env in ("CLAY_SKY130_PATH", "SKY130_ROOT"):
        if os.environ.get(env):
            candidates.append(Path(os.environ[env]))
    if os.environ.get("PDK_ROOT"):
        candidates.append(Path(os.environ["PDK_ROOT"]) / "sky130A")
        candidates.append(Path(os.environ["PDK_ROOT"]) / "sky130_pdk")
    candidates.extend([
        ROOT / "pdks" / "sky130A",
        ROOT / "pdks" / "sky130_pdk",
        Path.home() / ".volare" / "volare" / "sky130" / "versions",
        Path("/foss/pdks/sky130A"),
    ])
    for cand in candidates:
        if (cand / "libs.tech" / "ngspice").is_dir():
            return cand.resolve()
        if cand.name == "versions" and cand.is_dir():
            for child in sorted(cand.iterdir(), reverse=True):
                if (child / "sky130A" / "libs.tech" / "ngspice").is_dir():
                    return (child / "sky130A").resolve()
    return None


def detect_gf180mcu() -> Path | None:
    candidates = []
    for env in ("CLAY_GF180MCU_PATH", "GF180MCU_ROOT"):
        if os.environ.get(env):
            candidates.append(Path(os.environ[env]))
    if os.environ.get("PDK_ROOT"):
        candidates.append(Path(os.environ["PDK_ROOT"]) / "gf180mcuD")
        candidates.append(Path(os.environ["PDK_ROOT"]) / "gf180mcu")
    candidates.extend([
        ROOT / "pdks" / "gf180mcu",
        ROOT / "pdks" / "gf180mcuD",
        Path("/foss/pdks/gf180mcuD"),
    ])
    for cand in candidates:
        if (cand / "libraries" / "gf180mcu_fd_pr").is_dir() or (cand / "libs.tech" / "ngspice").is_dir():
            return cand.resolve()
    return None


def install_gf180(dest: Path) -> Path:
    dest.parent.mkdir(parents=True, exist_ok=True)
    if not dest.exists():
        print(f"[setup_open_pdks] Cloning google/gf180mcu-pdk into {dest} ...")
        subprocess.run(
            ["git", "clone", "--depth", "1", "https://github.com/google/gf180mcu-pdk.git", str(dest)],
            check=True,
        )
        subprocess.run(
            ["git", "-C", str(dest), "submodule", "update", "--init", "--depth", "1", "libraries/gf180mcu_fd_pr"],
            check=True,
        )
    return dest.resolve()


def install_sky130(pdk_root: Path) -> Path | None:
    volare = shutil.which("volare")
    if volare is None:
        print("[setup_open_pdks] `volare` not found. Install it with: pip install volare")
        print("  Then run: volare enable --pdk sky130 --pdk-root", pdk_root)
        return None
    pdk_root.mkdir(parents=True, exist_ok=True)
    print(f"[setup_open_pdks] Installing SKY130A via volare into {pdk_root} ...")
    subprocess.run([volare, "enable", "--pdk", "sky130", "--pdk-root", str(pdk_root)], check=True)
    return (pdk_root / "sky130A").resolve()


def write_clay_toml(sky130: Path | None, gf180: Path | None) -> Path:
    out = ROOT / "clay.toml"
    default_id = "sky130" if sky130 else "gf180mcu"
    default_root = (sky130.as_posix() if sky130 else (gf180.as_posix() if gf180 else "pdks/sky130A"))
    lines = [
        "# Auto-generated by scripts/setup_open_pdks.py",
        "[tool.clay]",
        f'pdk_id = "{default_id}"',
        f'pdk_root = "{default_root}"',
        'work_dir = "tmp_clay_rundir"',
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--detect", action="store_true", help="Detect installed SKY130 & GF180MCU PDKs")
    parser.add_argument("--install-gf180", action="store_true", help="Clone Apache-2.0 google/gf180mcu-pdk")
    parser.add_argument("--install-sky130", action="store_true", help="Fetch Apache-2.0 sky130A via volare")
    parser.add_argument("--write-config", action="store_true", help="Write clay.toml with resolved paths")
    args = parser.parse_args()

    sky = detect_sky130()
    gf = detect_gf180mcu()

    if args.install_gf180 and gf is None:
        gf = install_gf180(ROOT / "pdks" / "gf180mcu")
    if args.install_sky130 and sky is None:
        sky = install_sky130(ROOT / "pdks")

    print(f"SKY130   : {sky if sky else 'NOT FOUND (set CLAY_SKY130_PATH or run --install-sky130)'}")
    print(f"GF180MCU : {gf if gf else 'NOT FOUND (set CLAY_GF180MCU_PATH or run --install-gf180)'}")

    if args.write_config or args.install_gf180 or args.install_sky130:
        cfg = write_clay_toml(sky, gf)
        print(f"Wrote {cfg}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
